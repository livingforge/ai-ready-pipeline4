# ── PoC評価報告書 ─────────────────────────────────────────────────
def _poc(out: Path) -> Path:
    info = kit.DocInfo(doc_name="PoC 評価報告書", version="1.0",
                       date="2026/02/06", author="小島")
    wb = kit.new_book()
    kit.three_sheet(wb, info)

    ws = kit.add_sheet(wb, "1.概要")
    row = kit.heading(ws, 2, 2, "1. 評価の概要")
    kit.kv_table(ws, top=row, left=2, pairs=[
        ("目的", "採用する埋め込みモデルを決めること"),
        ("期間", "2025/12/15 - 2026/01/30"),
        ("評価データ", "保守マニュアル 200 問（カスタマーサポート部の実際の"
                     "問合せから作成）"),
        ("指標", "上位 5 件に正解が含まれる割合（Recall@5）"),
        ("比較対象", "Voyage AI の 5 モデル"),
        ("実施者", f"{kit.GROUP} 小島"),
    ], width=72, label_width=14)
    kit.set_print(ws, doc_name=info.doc_name)

    # ★ 仕込み A: voyage-4 を選んだ根拠はこの表にしかない。
    ws = kit.add_sheet(wb, "2.モデル比較")
    row = kit.heading(ws, 2, 2, "2. モデルの比較")
    row = kit.table(
        ws, top=row, left=2,
        caption="Recall@5（保守マニュアル 200 問）",
        header=["モデル", "提供形態", "次元", "文脈長", "用途",
                "Recall@5", "備考"],
        groups=[("", 2), ("仕様", 3), ("", 2)],
        rows=[[name, form, str(dim), f"{ctx:,}", use, score, note]
              for name, form, dim, ctx, use, score, note in spec.EMBED_MODELS],
        widths=[16, 26, 8, 10, 26, 10, 44], center_cols=(2, 3, 5))

    kit.note(ws, row, 2,
             "※ voyage-4 を既定として採用する。voyage-4-large は精度が"
             "高いが費用が 2.5 倍で、Recall@5 の差（0.04）に見合わない"
             "と判断した。")
    row += 2
    kit.note(ws, row, 2,
             "※ 極秘（機密区分 30）は外部 API を使えないため、"
             "オープンウェイトの voyage-4-nano しか選択肢が無い。"
             "精度が落ちることは法務部と合意済み。")
    row += 2
    kit.note(ws, row, 2,
             "※ voyage-law-2 は法務の文書で最も高いが、外部 API のみの"
             "提供のため極秘では使えない。営業本部（社外秘）での利用を"
             "検討する。")
    kit.set_print(ws, doc_name=info.doc_name)

    ws = kit.add_sheet(wb, "3.検索方式")
    row = kit.heading(ws, 2, 2, "3. 検索方式の比較")
    row = kit.table(
        ws, top=row, left=2,
        header=["方式", "Recall@5", "型番の検索", "所要（p95）", "所見"],
        rows=[
            ["ベクトルのみ", "0.82", "0.11", "180ms",
             "★ 型番がまったく当たらない。業務で使えない"],
            ["全文のみ（BM25）", "0.64", "0.98", "90ms",
             "言い換えに弱い。「異音がするときの対処」で当たらない"],
            ["ハイブリッド（RRF）", "0.88", "0.96", "310ms", "採用"],
            ["ハイブリッド + リランク", "0.93", "0.96", "620ms",
             "精度は最良だが費用が大きい。第2次リリースで検討"],
        ],
        widths=[24, 12, 12, 14, 52], center_cols=(1, 2, 3))
    kit.note(ws, row, 2,
             "※ 「型番の検索」は A-2210 形式の品番 40 問での Recall@5。")
    kit.set_print(ws, doc_name=info.doc_name)

    ws = kit.add_sheet(wb, "4.分割の検討")
    row = kit.heading(ws, 2, 2, "4. 分割の長さの検討")
    row = kit.table(
        ws, top=row, left=2,
        header=["分割の長さ", "重なり", "Recall@5", "チャンク数", "所見"],
        rows=[
            ["256 トークン", "32", "0.84", "2.1 倍", "文脈が切れて意味が取れない"],
            ["512 トークン", "64", "0.88", "1.0 倍", "★ 採用"],
            ["1024 トークン", "128", "0.85", "0.5 倍",
             "粒度が粗く、当たっても該当箇所が分からない"],
            ["見出し単位", "—", "0.79", "0.7 倍",
             "見出しの粒度が文書によってばらつく"],
        ],
        widths=[16, 10, 12, 14, 52], center_cols=(1, 2, 3))
    kit.note(ws, row, 2,
             "※ 512 トークン・重なり 64 を採用する。"
             "見出しの境界があればそちらを優先して切る。")
    kit.set_print(ws, doc_name=info.doc_name)

    ws = kit.add_sheet(wb, "5.結論")
    row = kit.heading(ws, 2, 2, "5. 結論と申し送り")
    kit.table(ws, top=row, left=2,
              header=["No", "決めたこと", "根拠"],
              rows=[
                  ["1", "既定のモデルは voyage-4", "2.モデル比較"],
                  ["2", "極秘は voyage-4-nano を社内 GPU でホストする",
                   "外部 API を使えないため"],
                  ["3", "ハイブリッド検索（RRF）を採用する", "3.検索方式"],
                  ["4", "分割は 512 トークン・重なり 64", "4.分割の検討"],
                  ["5", "リランクは第2次リリースで検討する",
                   "費用の見通しが立たないため"],
              ], widths=[5, 48, 34], center_cols=(0,))
    row += 8
    kit.note(ws, row, 2,
             "※ 本報告書の評価データ 200 問は PoC のために作成したもので、"
             "継続して測る仕組みは用意していない。"
             "サービス開始後の精度の変化は把握できない。")
    kit.set_print(ws, doc_name=info.doc_name)

    return kit.save(wb, out / "PoC評価報告書.xlsx")
