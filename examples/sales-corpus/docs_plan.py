# ── 議事録 ────────────────────────────────────────────────────────
def _minutes(out: Path, rel: str, header: list[tuple[str, list[tuple[str, str]]]],
             agenda: list[list[str]], todos: list[list[str]], doc_name: str) -> Path:
    """議事録は表紙を付けない（現場でも 1 シートで回す）。

    開催情報と議事内容はどちらも 3 列なので列幅を揃えて 1 シートに積む。
    宿題事項は列の組み立てが違う（内容が長く担当・期限が短い）ため別シートにする。
    """
    wb = xk.new_book()
    ws = xk.add_sheet(wb, "議事録")
    r = xk.heading(ws, 2, 2, doc_name)
    # 開催情報と議事内容で共有する列幅（大分類/No・項目/議題・内容）
    r = xk.kv_group_table(
        ws, top=r, left=2, groups=header, group_width=10, label_width=24, width=84
    )
    xk.table(
        ws,
        top=r,
        left=2,
        caption="議事内容",
        header=["No", "議題", "決定事項・討議内容"],
        rows=agenda,
        widths=[10, 24, 84],
        center_cols=(0,),
    )
    xk.set_print(ws, doc_name=doc_name)

    ws2 = xk.add_sheet(wb, "宿題事項")
    r = xk.heading(ws2, 2, 2, "宿題事項")
    xk.table(
        ws2,
        top=r,
        left=2,
        caption="宿題事項",
        groups=[("", 1), ("", 1), ("対応", 2)],
        header=["No", "内容", "担当", "期限"],
        rows=todos,
        widths=[8, 70, 16, 14],
        center_cols=(0, 2, 3),
        header_fill=xk.FILL_HEAD2,
    )
    xk.set_print(ws2, doc_name=doc_name)
    return xk.save(wb, out / rel)


