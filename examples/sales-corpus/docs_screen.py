def _screen_spec(out: Path, sub: str) -> Path:
    name = spec.SUBSYSTEM_NAME[sub]
    info = DocInfo(
        doc_name=f"画面仕様書（{name}）",
        subsystem=name,
        version="1.1",
        date="2025/08/29",
        revisions=REV,
    )
    screens = spec.screens_of(sub)
    role = {"ORD": "営業・管理者", "INV": "物流・管理者",
            "BIL": "経理・管理者", "CMN": "全ロール"}[sub]

    def body(wb, info):
        ws = xk.add_sheet(wb, "画面一覧")
        r = xk.heading(ws, 2, 2, f"{name} 画面一覧")
        xk.table(
            ws,
            top=r,
            left=2,
            caption=f"{name}　画面一覧",
            groups=[("", 1), ("", 1), ("", 1)],
            header=["画面名", "画面区分", "画面概要"],
            rows=[[sname, kind, desc] for sname, _s, kind, desc in screens],
            widths=[22, 10, 84],
            center_cols=(1,),
        )
        xk.set_print(ws, doc_name=info.doc_name)

        # レイアウト図（結合セルで描く）
        for sname, _s, _kind, _desc in screens:
            if sname in _MOCKS:
                wsl = xk.add_sheet(wb, f"{sname} レイアウト"[:31], grid=True)
                c = wsl.cell(row=2, column=2, value=f"{sname}　画面レイアウト")
                c.font = xk.F_SECTION
                xk.layout(wsl, _MOCKS[sname]())

        for sname, _s, kind, desc in screens:
            # 画面概要・イベント一覧・業務ルールは B〜E の列幅を共有できるので
            # 1 シートに積む（表領域が縦に 3 つ並ぶ状態を残す）。
            # 画面項目一覧だけは No 列を細くする必要があって揃わないため別シートにする。
            ws2 = xk.add_sheet(wb, sname[:31])
            r = xk.heading(ws2, 2, 2, sname)
            r = xk.kv_group_table(
                ws2,
                top=r,
                left=2,
                groups=[
                    ("画面の位置づけ", [
                        ("画面名", sname),
                        ("画面区分", kind),
                        ("機能概要", desc),
                        ("利用権限", role),
                    ]),
                    ("方式", [
                        ("排他制御", "楽観的排他。更新日時が一致しない場合は排他エラーとする"),
                        ("表示件数", "一覧は 1 ページ 50 件とし、ページ送りで表示する"),
                    ]),
                ],
                group_width=22,
                label_width=20,
                width=80,
            )
            events = EVENTS.get(sname)
            if events:
                r = xk.heading(ws2, r, 2, "イベント・処理一覧")
                r = xk.table(
                    ws2,
                    top=r,
                    left=2,
                    caption=f"{sname}　イベント・処理一覧",
                    groups=[("", 1), ("", 1), ("", 1), ("関連", 1)],
                    header=["イベント", "契機", "処理概要", "関連する業務ルール"],
                    rows=events,
                    widths=[22, 20, 80, 34],
                    header_fill=xk.FILL_HEAD2,
                )
            rules = [
                [kind_, rname, text]
                for rname, rsub, kind_, text in spec.BUSINESS_RULES
                if rsub == sub
            ]
            if rules:
                r = xk.heading(ws2, r, 2, "関連する業務ルール")
                xk.table(
                    ws2,
                    top=r,
                    left=2,
                    caption="関連する業務ルール（基本設計書より転記）",
                    header=["区分", "ルール名", "ルール内容"],
                    rows=rules,
                    widths=[22, 20, 80],
                    merge_cols=(0,),
                    center_cols=(0,),
                    header_fill=xk.FILL_HEAD2,
                )
            xk.set_print(ws2, doc_name=info.doc_name)

            ws3 = xk.add_sheet(wb, f"{sname} 項目"[:31])
            r = xk.heading(ws3, 2, 2, f"{sname}　画面項目一覧")
            items = ITEMS.get(sname) or _generic_items(sname)
            xk.table(
                ws3,
                top=r,
                left=2,
                caption=f"{sname}　画面項目一覧",
                groups=[("", 1), ("項目", 2), ("属性", 3), ("", 1), ("", 1)],
                header=["No", "項目名", "物理名", "種別", "型・桁", "必須", "初期値", "入力チェック・備考"],
                rows=[[str(i + 1)] + row for i, row in enumerate(items)],
                widths=[5, 20, 18, 8, 16, 8, 20, 64],
                center_cols=(0, 3, 4, 5),
            )
            xk.set_print(ws3, doc_name=info.doc_name)

    return xk.build(out, spec.path_of(sub, "基本設計", f"{name}_画面仕様書.xlsx"), info, body)


